// FTN Platform — one-time insertion of a compatibility banner on absorbed legacy product pages
// (FTN Consolidation closure wave, 2026-09-18). Explicit request: "If an absorbed legacy page
// still looks like a full independent product, add a clear compatibility banner or handoff."
//
// Deliberately excludes: /display/ (a real, physically-deployed kiosk screen meant to be opened
// and left full-screen with zero UI chrome -- a banner would actively harm that use case) and
// /radio/#ftn-epk (a fragment/anchor inside FTN Radio's own live product page, not a standalone
// legacy page of its own -- there is nothing to banner).
//
// Closure-wave correction (2026-09-18): /riddim/fire/ and /riddim/daw/ were originally excluded
// here too ("a mid-workflow banner would be more disruptive than useful"), but that reasoning did
// not survive scrutiny against /scenario-workspace/'s own successful banner (an equally tool-like,
// in-workflow page) -- both still look like full independent products to anyone landing directly
// on them, so both get the same thin, non-blocking banner treatment.
//
// Run: node scripts/add-absorbed-banners.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadRegistry } from './lib/registry-loader.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const Registry = loadRegistry(root);

const PAGES = [
  { file: 'riddim/index.html', id: 'riddim' },
  { file: 'scenario-workspace/index.html', id: 'scenario-workspace' },
  { file: 'learn/index.html', id: 'learn' },
  { file: 'parliament/index.html', id: 'parliament' },
  { file: 'kaiso/index.html', id: 'kaiso' },
  { file: 'tv/index.html', id: 'tv' },
  { file: 'top-picks/index.html', id: 'top-picks' },
  { file: 'riddim/fire/index.html', id: 'ftn-fire' },
  { file: 'riddim/daw/index.html', id: 'daw' },
];

const MARK_START = '<!-- FTN:ABSORBED-BANNER:START (generated by scripts/add-absorbed-banners.mjs) -->';
const MARK_END = '<!-- FTN:ABSORBED-BANNER:END -->';

function esc(v) { return String(v == null ? '' : v).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c])); }

let changed = 0;
for (const page of PAGES) {
  const product = Registry.get(page.id);
  if (!product || !product.absorbedInto) throw new Error(`${page.id}: expected a real absorbedInto product`);
  const parent = Registry.get(product.absorbedInto);
  const file = resolve(root, page.file);
  const html = readFileSync(file, 'utf8');
  if (html.includes(MARK_START)) { console.log(`${page.file}: banner already present, skipping.`); continue; }

  const banner = MARK_START +
    `<style>.ftn-absorbed-banner{background:#11151a;color:#f2f3f5;padding:10px 16px;font:600 13px/1.5 Inter,sans-serif;text-align:center}` +
    `.ftn-absorbed-banner a{color:#ff4d4d;font-weight:800;text-decoration:none}.ftn-absorbed-banner a:hover,.ftn-absorbed-banner a:focus-visible{text-decoration:underline}` +
    `.ftn-absorbed-banner p{margin:0;max-width:960px;margin-inline:auto}</style>` +
    `<div class="ftn-absorbed-banner" role="note">` +
    `<p>This page is now part of <strong>${esc(parent.name)}</strong>. Nothing here has been removed — ` +
    `<a href="${esc(parent.route)}">open ${esc(parent.name)}</a> for the connected experience, or continue below.</p>` +
    `</div>` + MARK_END;

  const mainOpenRe = /<main[^>]*>/;
  const match = html.match(mainOpenRe);
  if (!match) throw new Error(`${page.file}: no <main> tag found to insert the banner after`);
  const insertAt = match.index + match[0].length;
  const next = html.slice(0, insertAt) + banner + html.slice(insertAt);
  writeFileSync(file, next);
  changed += 1;
  console.log(`${page.file}: banner inserted -> ${parent.name} (${parent.route})`);
}
console.log(`\n${changed} page(s) updated.`);
