// FTN Platform — service-worker route-policy synchronization script.
//
// Phase 3 service-worker route-policy consolidation (see GOVERNANCE/FTN_Repair_Ledger_2026-08-24.md).
// service-worker.js's PRIVATE and NEVER regexes are generated from two sources so neither can
// silently drift from the other or from hand-edited source:
//   PRIVATE -- registered FTN products whose own js/product-registry-data.js metadata says
//     publicVisibility===false, status is PRIVATE/VAULTED, or authRequirement !== 'guest'.
//   NEVER   -- data/route-policy.mjs's non-product routes (account/auth infra, admin console,
//     other-application mount points, and the one 'prefix'-type caching-only entry; the
//     'contains'-type /functions/v1/ entry stays its own separate, unchanged line -- see that
//     file's comment for why).
//
// *** Generating this from a canonical source is a maintainability guarantee, not a security
// guarantee. *** Nothing in service-worker.js is an authorization boundary -- see
// data/route-policy.mjs's own top comment and .claude/context/security-ops.md.
//
// Run: node scripts/sync-service-worker.mjs           -- writes service-worker.js.
// Run: node scripts/sync-service-worker.mjs --check    -- reports drift, exits 1 if it would change.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';
import { loadRegistry as loadRegistryShared } from './lib/registry-loader.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { ACCOUNT_AUTH_ROUTES, ADMIN_ROUTES, OTHER_APPLICATION_ROUTES, CACHING_ONLY_ROUTES } =
  await import(pathToFileURL(resolve(root, 'data/route-policy.mjs')));

function pathSegment(route) {
  // '/mission-control/' -> 'mission-control'; '/community-connect/app' -> 'community-connect/app'
  return String(route).replace(/^\/+/, '').replace(/\/+$/, '');
}

function regexEscape(segment) {
  // Escapes regex metacharacters AND '/', which must be escaped inside a `/.../ ` regex literal
  // (JS regex literal syntax, not regex semantics) or it would prematurely close the pattern.
  return segment.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/\//g, '\\/');
}

// authRequirement values that mean "this route can render an authenticated/personalized response
// and must never be cached" -- an explicit allowlist, not "anything other than 'guest'", because
// 'none' (a real value: fully public, no account at all -- e.g. FTN Screen's Display Mode) is
// EVEN MORE public than 'guest', not less, and must not be swept into this exclusion.
const CACHE_UNSAFE_AUTH_REQUIREMENTS = ['mixed', 'authenticated', 'private'];

function derivePrivateProductSegments(Registry) {
  return Registry.all()
    .filter((p) => p.publicVisibility === false || ['PRIVATE', 'VAULTED'].includes(p.status) || CACHE_UNSAFE_AUTH_REQUIREMENTS.includes(p.authRequirement))
    .map((p) => pathSegment(p.route))
    .filter(Boolean)
    .sort();
}

function deriveNeverSegments() {
  const prefixEntries = [...ACCOUNT_AUTH_ROUTES, ...ADMIN_ROUTES, ...OTHER_APPLICATION_ROUTES, ...CACHING_ONLY_ROUTES]
    .filter((e) => e.match === 'prefix');
  return prefixEntries.map((e) => pathSegment(e.path)).sort();
}

function buildRegexLiteral(segments) {
  return '/^\\/(' + segments.map(regexEscape).join('|') + ')(\\/|$)/';
}

const MARK_START = '// FTN:SW-POLICY:START (generated by scripts/sync-service-worker.mjs -- do not hand-edit, edit js/product-registry-data.js\'s navPlacement/authRequirement fields or data/route-policy.mjs instead) //';
const MARK_END = '// FTN:SW-POLICY:END //';

function applyRegion(source, generated) {
  const startIdx = source.indexOf(MARK_START);
  const endIdx = source.indexOf(MARK_END);
  if (startIdx === -1 || endIdx === -1 || endIdx < startIdx) {
    throw new Error('service-worker.js is missing the FTN:SW-POLICY marker pair -- expected both markers to already be present around the PRIVATE/NEVER declarations');
  }
  return source.slice(0, startIdx) + MARK_START + '\n' + generated + '\n' + MARK_END + source.slice(endIdx + MARK_END.length);
}

const Registry = loadRegistryShared(root);
const privateSegments = derivePrivateProductSegments(Registry);
const neverSegments = deriveNeverSegments();

if (!privateSegments.length) throw new Error('No PRIVATE product routes derived from the registry -- refusing to write an empty exclusion list (this would almost certainly be a bug, not a real state)');
if (!neverSegments.length) throw new Error('No NEVER routes derived from data/route-policy.mjs -- refusing to write an empty exclusion list');

const generated = 'var PRIVATE=' + buildRegexLiteral(privateSegments) + ';\nvar NEVER=' + buildRegexLiteral(neverSegments) + ';';

const path = resolve(root, 'service-worker.js');
const source = readFileSync(path, 'utf8');
const next = applyRegion(source, generated);

const args = process.argv.slice(2);
if (args.includes('--check')) {
  if (next !== source) {
    console.error('service-worker.js PRIVATE/NEVER routes have drifted from the Product Registry / data/route-policy.mjs.');
    console.error('Run: node scripts/sync-service-worker.mjs');
    process.exit(1);
  }
  console.log(`service-worker.js route policy is current (${privateSegments.length} private product route(s), ${neverSegments.length} non-product route(s)).`);
} else {
  writeFileSync(path, next);
  console.log(`Synced service-worker.js: PRIVATE=[${privateSegments.join(', ')}] NEVER=[${neverSegments.join(', ')}]`);
}
