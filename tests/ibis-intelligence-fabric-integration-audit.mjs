import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const ctx={window:{},console,setTimeout,clearTimeout,Date,Map,Set,Intl,AbortController,fetch:async()=>{throw new Error('network must not be used');}};
ctx.window.window=ctx.window;ctx.window.console=console;ctx.window.setTimeout=setTimeout;ctx.window.clearTimeout=clearTimeout;ctx.window.Date=Date;ctx.window.Map=Map;ctx.window.Set=Set;ctx.window.Intl=Intl;ctx.window.AbortController=AbortController;ctx.window.fetch=ctx.fetch;
vm.createContext(ctx);
function load(file){vm.runInContext(fs.readFileSync(file,'utf8'),ctx,{filename:file});}
load('js/ibis-capability-taxonomy.js');
load('js/ibis-provider-registry.js');
load('js/ibis-intelligence-fabric-extension.js');
load('js/ibis-eligibility.js');
load('js/ibis-math.js');
load('js/ibis-correlation-engine.js');
load('js/ibis-capital-intelligence.js');
