load('js/ibis-foresight-engine.js');
load('js/ibis-client.js');
load('js/ibis-intelligence-client-extension.js');
const F=ctx.window.FTN;
assert.equal(F.IbisIntelligenceFabricExtension.applied,true);
assert.equal(F.CapabilityTaxonomy.isRecognized('CORRELATION_ANALYSIS'),true);
assert.equal(F.CapabilityTaxonomy.isRecognized('FORESIGHT_GENERATE'),true);
assert.equal(F.CapabilityTaxonomy.groupOf('CAPITAL_SCENARIO'),'INTELLIGENCE');
assert.equal(F.IbisProviders.byCapability('CORRELATION_ANALYSIS')[0].id,'ibis-local-correlation-engine');
assert.equal(F.IbisEligibility.find('CAPITAL_SCENARIO',{}).length,1);
const a={id:'a',label:'A',unit:'index',frequency:'ANNUAL',source:{publisher:'A'},periods:['2020','2021','2022','2023','2024'],values:[1,2,3,4,5]};
const b={id:'b',label:'B',unit:'count',frequency:'ANNUAL',source:{publisher:'B'},periods:['2020','2021','2022','2023','2024'],values:[2,4,6,8,10]};
const corr=await F.IbisClient.request({capability:'CORRELATION_ANALYSIS',payload:{a,b}});
assert.equal(corr.success,true);assert.equal(corr.result.success,true);assert(Math.abs(corr.result.r-1)<1e-12);assert.equal(corr.provenance.capability,'CORRELATION_ANALYSIS');assert.equal(corr.provenance.provider,'ibis-local-correlation-engine');
const capital=await F.IbisClient.request({capability:'CAPITAL_SCENARIO',payload:{monthlyIncome:35000,grossYieldPercent:5}});
assert.equal(capital.success,true);assert.equal(capital.result.success,true);assert.equal(capital.result.capitalToPreserveNominalPrincipal,8400000);assert.equal(capital.provenance.provider,'ibis-local-capital-intelligence');
const stored=await F.IbisClient.request({capability:'INTENT_STORE',payload:{intent:{id:'intent-1',mode:'NEED',categories:['funding'],keywords:['statistics'],geographies:['caribbean']}}});
assert.equal(stored.success,true);assert.equal(stored.result.success,true);assert.equal(stored.result.intent.visibility,'PRIVATE');
const finding={id:'f1',title:'Caribbean statistics funding',type:'MONEY',status:'OPEN',organization:'Fund',geography:'Caribbean',sourceUrl:'https://example.org/f1',verifiedAt:'2026-09-07',deadline:'2026-09-20',summary:'Funding for statistics projects'};
const matched=await F.IbisClient.request({capability:'OPPORTUNITY_MATCH',payload:{intentId:'intent-1',findings:[finding]}});
assert.equal(matched.success,true);assert.equal(matched.result.success,true);assert.equal(matched.result.matches.length,1);assert.equal(matched.result.matches[0].eligibility,'NOT_ASSESSED');
const foresight=await F.IbisClient.request({capability:'FORESIGHT_GENERATE',payload:{opportunityMatches:matched.result.matches,now:'2026-09-07T12:00:00Z'}});
assert.equal(foresight.success,true);assert.equal(foresight.result.success,true);assert.equal(foresight.result.probabilitiesEstimated,false);assert.equal(foresight.result.candidates[0].priority,'PREPARE_NOW');assert.equal(foresight.provenance.provider,'ibis-local-foresight-engine');
console.log('ibis Intelligence Fabric integration: math, correlation, capital, private intent, opportunity matching and Foresight route through eligibility + IbisClient + provenance with zero network calls.');
